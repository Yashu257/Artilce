/**
 * assistant.ts — answerQuestion(): retrieve -> ground -> generate -> persist.
 *
 * Implements the plug-in contract in ./types.ts:
 *   export const ASSISTANT_AVAILABLE = true
 *   export const handleChat: AssistantHandler
 *
 * Flow:
 *   1. Retrieve top-6 chunks above the provider threshold.
 *   2. If none: return the EXACT insufficient-information sentence +
 *      disclaimer. No citations are invented.
 *   3. Otherwise: build a grounded prompt (document text treated as
 *      untrusted data; injection guard in prompts.ts) and
 *        - call OpenAI gpt-4o-mini if OPENAI_API_KEY is set, else
 *        - call Gemini gemini-1.5-flash if GEMINI_API_KEY is set, else
 *        - extractive fallback: compose the answer ONLY from retrieved
 *          excerpts, labelled as an extractive summary. No invented claims.
 *   4. Always append the medical disclaimer.
 *   5. Persist Conversation + Message rows via Prisma when the DB is
 *      reachable; if not, log honestly and still return the answer.
 *   6. Streaming: answerQuestionStream() calls onToken with the answer
 *      in small pieces so the SSE route can stream it; the extractive
 *      fallback streams its composed text the same way.
 */
import { prisma } from '../lib/prisma';
import { logger } from '../lib/logger';
import { getEmbeddingProvider, tokenize } from './embeddings';
import { retrieve, type RetrievedChunk } from './retrieval';
import {
  INSUFFICIENT_INFORMATION,
  MEDICAL_DISCLAIMER,
  SYSTEM_PROMPT,
  buildGroundedPrompt,
} from './prompts';
import type { AssistantHandler, ChatRequest, ChatResult } from './types';

export const ASSISTANT_AVAILABLE = true;

/**
 * Response mode — the distinction required by the product brief:
 * - 'llm': answer generated by OpenAI / Gemini from retrieved context.
 * - 'local-retrieval': no external LLM key is configured. Evidence was
 *   retrieved from the PDFs and the answer was composed ONLY from the
 *   retrieved excerpts. Never claim LLM generation in this mode.
 * `engine` names the concrete mechanism (model id, 'extractive', or
 * 'insufficient' when nothing cleared the threshold).
 */
export type AssistantMode = 'llm' | 'local-retrieval';

export interface AssistantAnswer extends ChatResult {
  mode: AssistantMode;
  engine: string;
  provider: string;
}

const OPENAI_CHAT_MODEL = 'gpt-4o-mini';
const GEMINI_CHAT_MODEL = 'gemini-3.5-flash';

function withDisclaimer(body: string): string {
  return `${body.trim()}\n\n${MEDICAL_DISCLAIMER}`;
}

/**
 * Extractive fallback: answer composed ONLY from retrieved excerpts.
 * Each bullet quotes the leading sentence of one excerpt and cites it.
 * Nothing is added that is not in the excerpts.
 */
export function extractiveAnswer(question: string, chunks: RetrievedChunk[]): string {
  const queryTerms = new Set(tokenize(question));
  // Prefer the first substantive sentence that mentions a query term —
  // slide decks are full of header/footer fragments ("Vol.: ...",
  // "1053 CARREÑO 1234") and quoting those as the answer is truthful
  // but useless. The sentence still comes verbatim from the excerpt.
  const pickSentence = (excerpt: string): string => {
    const sentences = excerpt.split(/(?<=[.!?])\s+/).map((s) => s.trim()).filter(Boolean);
    const withTerm = sentences.find(
      (s) => s.length >= 40 && [...queryTerms].some((t) => s.toLowerCase().includes(t)),
    );
    return withTerm ?? sentences.find((s) => s.length >= 40) ?? sentences[0] ?? excerpt;
  };
  const lines = chunks.map((c, i) => {
    const sentence = pickSentence(c.excerpt);
    return `- ${sentence} [${i + 1}] (${c.documentName}, p. ${c.page}, ${c.section})`;
  });
  return (
    `Local retrieval mode — evidence retrieved from PDFs, answer composed from retrieved excerpts, no external LLM.\n\n` +
    `Based on the available Cipla medical resources, the following is relevant to "${question}":\n\n` +
    lines.join('\n')
  );
}

async function generateWithLlm(
  question: string,
  chunks: RetrievedChunk[],
): Promise<{ text: string; mode: string } | null> {
  const provider = getEmbeddingProvider();
  const userPrompt = buildGroundedPrompt(question, chunks);

  if (provider === 'openai' && process.env.OPENAI_API_KEY) {
    const { default: OpenAI } = await import('openai');
    const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });
    const res = await client.chat.completions.create({
      model: OPENAI_CHAT_MODEL,
      temperature: 0,
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        { role: 'user', content: userPrompt },
      ],
    });
    return { text: res.choices[0]?.message?.content?.trim() ?? '', mode: 'llm-openai' };
  }

  if (process.env.GEMINI_API_KEY) {
    try {
      const { GoogleGenerativeAI } = await import('@google/generative-ai');
      const client = new GoogleGenerativeAI(process.env.GEMINI_API_KEY as string);
      const model = client.getGenerativeModel({ model: GEMINI_CHAT_MODEL, systemInstruction: SYSTEM_PROMPT });
      const res = await model.generateContent({
        contents: [{ role: 'user', parts: [{ text: userPrompt }] }],
      });
      return { text: res.response.text().trim(), mode: 'llm-gemini' };
    } catch (err) {
      logger.warn('[assistant] Gemini generation failed, falling back to extractive', { error: String(err) });
      return null;
    }
  }

  return null;
}

async function persistConversation(
  userId: string,
  conversationId: string | undefined,
  question: string,
  answer: string,
  citations: RetrievedChunk[],
): Promise<string> {
  try {
    let convId = conversationId;
    if (convId) {
      const existing = await prisma.conversation.findFirst({ where: { id: convId, userId } });
      if (!existing) convId = undefined;
    }
    if (!convId) {
      const title = question.length > 80 ? question.slice(0, 80) + '…' : question;
      const created = await prisma.conversation.create({ data: { userId, title } });
      convId = created.id;
    } else {
      await prisma.conversation.update({ where: { id: convId }, data: { updatedAt: new Date() } });
    }
    const citationsJson = JSON.stringify(citations);
    await prisma.message.create({ data: { conversationId: convId, role: 'user', content: question } });
    await prisma.message.create({
      data: { conversationId: convId, role: 'assistant', content: answer, citationsJson },
    });
    return convId;
  } catch (err) {
    logger.warn('[assistant] Failed to persist conversation (continuing without DB)', {
      error: String(err),
    });
    return conversationId ?? `local-${Date.now()}`;
  }
}

export async function answerQuestion(
  userId: string,
  conversationId: string | undefined,
  question: string,
): Promise<AssistantAnswer> {
  const cleanQuestion = question.trim();
  if (!cleanQuestion) throw new Error('Question must not be empty.');

  const { chunks, provider } = await retrieve(cleanQuestion, 6);

  if (chunks.length === 0) {
    const answer = withDisclaimer(INSUFFICIENT_INFORMATION);
    const convId = await persistConversation(userId, conversationId, cleanQuestion, answer, []);
    return { answer, citations: [], conversationId: convId, mode: 'local-retrieval', engine: 'insufficient', provider };
  }

  const llm = await generateWithLlm(cleanQuestion, chunks);
  let answer: string;
  let mode: AssistantMode;
  let engine: string;
  if (llm && llm.text) {
    answer = withDisclaimer(llm.text);
    mode = 'llm';
    engine = llm.mode === 'llm-openai' ? `openai-${OPENAI_CHAT_MODEL}` : `gemini-${GEMINI_CHAT_MODEL}`;
  } else {
    answer = withDisclaimer(extractiveAnswer(cleanQuestion, chunks));
    mode = 'local-retrieval';
    engine = 'extractive';
  }

  const convId = await persistConversation(userId, conversationId, cleanQuestion, answer, chunks);
  return { answer, citations: chunks, conversationId: convId, mode, engine, provider };
}

/**
 * Route plug-in: the contract in ./types.ts. The returned object carries
 * the ChatResult fields plus `mode` / `engine` / `provider` at runtime,
 * so the HTTP layer can expose the llm vs local-retrieval distinction
 * in every chat response.
 */
export const handleChat: AssistantHandler = async (req: ChatRequest): Promise<ChatResult> => {
  return answerQuestion(req.userId, req.conversationId, req.question);
};

/** Streaming variant: emits the final answer text in ~120-char pieces. */
export async function answerQuestionStream(
  userId: string,
  conversationId: string | undefined,
  question: string,
  onToken: (token: string) => void,
): Promise<AssistantAnswer> {
  const result = await answerQuestion(userId, conversationId, question);
  const text = result.answer;
  for (let i = 0; i < text.length; i += 120) {
    onToken(text.slice(i, i + 120));
  }
  return result;
}
