"use client";
import { Cpu, Database } from "lucide-react";
import type { RetrievalMode } from "../lib/types";

/**
 * Retrieval-mode badge (req. 3). The mode comes only from the backend response
 * (SSE `mode` event / JSON `mode` field). Never claim LLM when the backend
 * reports local retrieval.
 */
export default function RetrievalModeBadge({ mode }: { mode: RetrievalMode | string }) {
  if (mode === "llm") {
    return (
      <span className="inline-flex items-center gap-1.5 rounded-full bg-primary/10 px-2.5 py-1 text-xs font-medium text-primary">
        <Cpu className="h-3.5 w-3.5" /> LLM mode — answer generated by OpenAI/Gemini from retrieved context
      </span>
    );
  }
  return (
    <span className="inline-flex items-center gap-1.5 rounded-full bg-amber-50 px-2.5 py-1 text-xs font-medium text-warning">
      <Database className="h-3.5 w-3.5" /> Local retrieval mode — evidence retrieved from PDFs, answer composed from retrieved excerpts, no external LLM
    </span>
  );
}
